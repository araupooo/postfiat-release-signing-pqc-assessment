#!/bin/sh
# Regenerate every derived output of this pack from scratch (offline).
#   1. build_derived.py  -> results/timing_table.csv/.md,
#                            results/size_table.csv/.md,
#                            results/cost_model.json/.csv,
#                            results/summary.txt, docs/index.html
#                            (from the vendored results/signing_*.json
#                            and results/environment.json; no network)
#   2. verify_digests.sh -> SHA256SUMS regenerated and verified
#
# To re-run the signing measurements themselves (not part of offline
# reproduction — timings vary run to run), use:
#   bash harness/build_signing.sh   (needs the liboqs 0.16.0 minimal
#     build with SLH-DSA and the PQClean sources at the pinned commit;
#     see REPRODUCTION.md)
#   bash harness/run_signing.sh
# then re-run this script to re-derive the tables.
#
# results/run_log.txt is NOT regenerated by this script: it is the raw
# console log of a fresh-copy reproduction run, captured by whoever
# runs this script in a fresh copy (see REPRODUCTION.md). Likewise
# results/digest_check_output.txt is the raw output of
# `bash verify_digests.sh --check`, captured after the run log is
# placed; this script regenerates SHA256SUMS itself (which covers
# both files) and verifies it.
#
# NOTE: scripts are invoked via `bash` (not `./`) on purpose: files
# uploaded through the GitHub web UI lose their executable bit, so a
# fresh clone would fail with exit 126 if run_all.sh called
# ./verify_digests.sh directly.
set -eu
PACK_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
cd "$PACK_DIR"
python3 build_derived.py
bash verify_digests.sh
echo "run_all.sh: OK"
